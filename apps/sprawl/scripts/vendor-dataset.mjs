// Build-time data pipeline (ADR 0022): fetch PeeringDB, aggregate connected capacity per facility,
// and write a dated snapshot into the repo. The deck stays 100% client-side — this runs at build
// time (locally or on the scheduled CI drift job), never in the browser. PeeringDB sends no CORS
// allow header, which is exactly why the data is vendored rather than fetched live.
//
//   node scripts/vendor-dataset.mjs   → writes src/data/dataset-YYYY-MM.json + snapshot.ts
//
// Drift is detected by the scheduled CI job (vendor-sprawl-dataset.yml): it runs this, then opens a
// PR if the committed files changed. The committed dataset is a versioned artifact — its provenance
// and movement live in git history.

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { facilityPoints } from './aggregate.mjs'

const API = 'https://www.peeringdb.com/api'
const DATA_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data')

/** Fetch one PeeringDB endpoint, selecting only the fields we aggregate to keep the payload small. */
async function fetchRows(endpoint, fields) {
  const res = await fetch(`${API}/${endpoint}?fields=${fields.join(',')}`, {
    headers: { Accept: 'application/json' },
  })
  if (!res.ok) {
    throw new Error(`PeeringDB ${endpoint} → HTTP ${res.status}`)
  }
  const body = await res.json()
  return body.data
}

/** `YYYY-MM` for the current month — the snapshot's dated identity (ADR 0022). */
function currentMonth() {
  const now = new Date()
  return `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, '0')}`
}

async function build() {
  const [facilities, ixfacs, netixlans] = await Promise.all([
    fetchRows('fac', ['id', 'city', 'country', 'latitude', 'longitude']),
    fetchRows('ixfac', ['ix_id', 'fac_id']),
    fetchRows('netixlan', ['ix_id', 'speed']),
  ])

  const points = facilityPoints(facilities, ixfacs, netixlans)
  if (points.length === 0) {
    throw new Error('aggregation produced 0 points — refusing to write an empty snapshot')
  }

  const asOf = currentMonth()
  const dataset = {
    asOf,
    measure: 'connected capacity (Mbps)',
    source: 'PeeringDB — netixlan.speed summed per exchange, attributed to its facilities (ixfac)',
    points,
  }
  return { asOf, dataset }
}

/** The generated pointer: `dataset.ts` imports this, so the dated filename is captured in one place
 *  the drift PR diff makes obvious. Regenerated whenever the snapshot is re-vendored. */
function snapshotModule(asOf) {
  return `// GENERATED by scripts/vendor-dataset.mjs — do not edit by hand.
// Regenerate with \`npm run vendor:dataset\`. The dated snapshot is a versioned artifact (ADR 0022).
import type { Dataset } from '../atlas/types'
import dataset from './dataset-${asOf}.json'

export const SNAPSHOT: Dataset = dataset as Dataset
`
}

/** Compact JSON — the points array is large; pretty-printing would triple the committed size for no
 *  gain (the diff that matters is per-point capacity, and git shows it either way). */
function serialize(dataset) {
  return `${JSON.stringify(dataset)}\n`
}

const { asOf, dataset } = await build()
writeFileSync(join(DATA_DIR, `dataset-${asOf}.json`), serialize(dataset))
writeFileSync(join(DATA_DIR, 'snapshot.ts'), snapshotModule(asOf))
// biome-ignore lint/suspicious/noConsole: build-time CLI script — stdout is the deliberate output.
console.log(`wrote ${dataset.points.length} points → dataset-${asOf}.json + snapshot.ts`)
